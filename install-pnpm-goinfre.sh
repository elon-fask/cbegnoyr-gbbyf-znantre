#!/usr/bin/env bash
# Install pnpm standalone into /goinfre/$USER/pnpm — no sudo, no /home persistence.
set -euo pipefail

GOINFRE="/goinfre/$USER"
PNPM_HOME_DIR="$GOINFRE/pnpm"
ENV_FILE="$GOINFRE/pnpm-env.sh"
PNPM_VERSION="${PNPM_VERSION:-latest-11}"
FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1

[[ -t 1 ]] && { B=$'\033[1m' G=$'\033[32m' Y=$'\033[33m' R=$'\033[31m' C=$'\033[36m' N=$'\033[0m'; } ||
  { B= G= Y= R= C= N=; }
ok() { printf "${G}[ OK ]${N} %s\n" "$*"; }
info() { printf "${C}[INFO]${N} %s\n" "$*"; }
warn() { printf "${Y}[WARN]${N} %s\n" "$*"; }
die() {
  printf "${R}[FAIL]${N} %s\n" "$*" >&2
  exit 1
}

[[ -d /goinfre ]] || die "/goinfre does not exist on this workstation"
mkdir -p "$GOINFRE"

if [[ -x "$PNPM_HOME_DIR/pnpm" && "$FORCE" -eq 0 ]]; then
  ok "pnpm already installed ($("$PNPM_HOME_DIR/pnpm" --version 2>/dev/null || echo '?'))"
  info "Use --force to reinstall"
  exit 0
fi

info "Installing pnpm $PNPM_VERSION into $PNPM_HOME_DIR"
mkdir -p "$PNPM_HOME_DIR"

# Snapshot ~/.zshrc (and ~/.bashrc) so we can restore them after the installer
# inevitably appends a pnpm block. This is the workaround for pnpm 11 not
# supporting PNPM_NO_MODIFY_PATH.
ZSHRC_BAK=""
BASHRC_BAK=""
if [[ -f "$HOME/.zshrc" ]]; then
  ZSHRC_BAK="$(mktemp)"
  cp "$HOME/.zshrc" "$ZSHRC_BAK"
fi
if [[ -f "$HOME/.bashrc" ]]; then
  BASHRC_BAK="$(mktemp)"
  cp "$HOME/.bashrc" "$BASHRC_BAK"
fi
cleanup_rc_files() {
  [[ -n "$ZSHRC_BAK" && -f "$ZSHRC_BAK" ]] && cp "$ZSHRC_BAK" "$HOME/.zshrc"
  [[ -n "$BASHRC_BAK" && -f "$BASHRC_BAK" ]] && cp "$BASHRC_BAK" "$HOME/.bashrc"
  rm -f "$ZSHRC_BAK" "$BASHRC_BAK"
}
trap cleanup_rc_files EXIT

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"; cleanup_rc_files' EXIT

# Download the installer
if command -v curl >/dev/null 2>&1; then
  curl -fsSL https://get.pnpm.io/install.sh -o "$tmp/install.sh" ||
    die "Could not download installer"
elif command -v wget >/dev/null 2>&1; then
  wget -qO "$tmp/install.sh" https://get.pnpm.io/install.sh ||
    die "Could not download installer"
else
  die "Neither curl nor wget available"
fi

# Run the installer WITHOUT PNPM_NO_MODIFY_PATH (unsupported on pnpm 11).
# The trap above will restore ~/.zshrc and ~/.bashrc immediately after it exits.
env \
  PNPM_HOME="$PNPM_HOME_DIR" \
  PNPM_VERSION="$PNPM_VERSION" \
  XDG_DATA_HOME="$GOINFRE/.local/share" \
  XDG_CACHE_HOME="$GOINFRE/.cache" \
  XDG_CONFIG_HOME="$GOINFRE/.config" \
  XDG_STATE_HOME="$GOINFRE/.local/state" \
  sh "$tmp/install.sh" || die "pnpm installer failed"

[[ -x "$PNPM_HOME_DIR/pnpm" ]] || die "Installer finished but $PNPM_HOME_DIR/pnpm is missing"
ok "pnpm $("$PNPM_HOME_DIR/pnpm" --version) installed"

# Write the environment file that users source to activate pnpm.
cat >"$ENV_FILE" <<EOF
# pnpm environment — generated by install-pnpm-goinfre.sh
export PNPM_HOME="$PNPM_HOME_DIR"
export XDG_DATA_HOME="$GOINFRE/.local/share"
export XDG_CACHE_HOME="$GOINFRE/.cache"
export XDG_CONFIG_HOME="$GOINFRE/.config"
export XDG_STATE_HOME="$GOINFRE/.local/state"
case ":\$PATH:" in
  *":\$PNPM_HOME/bin:"*) ;;
  *) export PATH="\$PNPM_HOME/bin:\$PNPM_HOME:\$PATH" ;;
esac
EOF
chmod 644 "$ENV_FILE"
ok "Environment file written: $ENV_FILE"

# Pin store and global bin explicitly
(
  export PNPM_HOME="$PNPM_HOME_DIR"
  export PATH="$PNPM_HOME_DIR/bin:$PNPM_HOME_DIR:$PATH"
  "$PNPM_HOME_DIR/pnpm" config set --global store-dir "$PNPM_HOME_DIR/store" 2>/dev/null || true
  "$PNPM_HOME_DIR/pnpm" config set --global global-bin-dir "$PNPM_HOME_DIR/bin" 2>/dev/null || true
) || true

echo
ok "Installation complete"
echo "  pnpm binary : $PNPM_HOME_DIR/pnpm"
echo "  store       : $PNPM_HOME_DIR/store"
echo "  global bins : $PNPM_HOME_DIR/bin"
echo "  cache       : $GOINFRE/.cache/pnpm"
echo
info "Activate in this shell:"
echo "    source $ENV_FILE"
info "Then verify:"
echo "    pnpm --version && pnpm store path && pnpm bin -g"
